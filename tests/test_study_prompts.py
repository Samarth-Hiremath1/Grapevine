"""The underspecification study still reproduces from this code.

Two things have to hold for the committed runs to mean anything:

1. Every task regenerates byte-identically from its seed.
2. Every prompt the code would build for those episodes is byte-identical to
   the prompt that was actually sent.

(2) is not directly observable — the episodes record responses, not prompts — so
it is pinned by the digests in ``studies/underspecification/prompts_golden.json``
and the full text in ``prompts_sample.md``, both generated by
``studies.underspecification.freeze_prompts``. These tests re-derive both and
fail on any difference, including a negative control that proves they can fail.
"""

from __future__ import annotations

import json

import pytest

from grapevine.rollout import engine
from studies.underspecification import freeze_prompts
from studies.underspecification.prompts import digest, env_for_run, reconstruct, task_for

STUDY_DIR = freeze_prompts.STUDY_DIR

#: Every committed episode file, as ``(run, condition, path)``.
EPISODE_FILES = [
    pytest.param(path, id=f"{path.parent.name}/{path.stem.removeprefix('episodes_')}")
    for path in freeze_prompts._episode_files(STUDY_DIR)
]


def test_study_has_committed_runs() -> None:
    """Guard against the glob silently matching nothing after a move."""
    assert len(EPISODE_FILES) == 14, "expected 14 committed (run, condition) episode files"


@pytest.mark.parametrize("path", EPISODE_FILES)
def test_tasks_regenerate_from_their_seeds(path) -> None:  # type: ignore[no-untyped-def]
    """Each episode's task regenerates identically from its recorded seed.

    ``task_for`` raises if the task id, question, options, gold answer or
    required facts differ, so this covers the whole task payload.
    """
    env = env_for_run(path.parent)
    episodes = freeze_prompts._load(path)
    assert episodes, f"{path} is empty"
    for episode in episodes:
        task_for(episode, env)  # raises on any mismatch


@pytest.mark.parametrize("path", EPISODE_FILES)
def test_prompts_match_the_frozen_digest(path) -> None:  # type: ignore[no-untyped-def]
    """Reconstructed prompts hash to the committed digest for this condition."""
    golden = json.loads(
        freeze_prompts.GOLDEN_PATH.read_text(encoding="utf-8")
    )["conditions"]
    key = freeze_prompts._key(path)
    assert key in golden, f"{key} has no frozen digest; rerun freeze_prompts"
    episodes = freeze_prompts._load(path)
    assert len(episodes) == golden[key]["n_episodes"]
    assert digest(episodes, env_for_run(path.parent)) == golden[key]["sha256"], (
        f"prompts for {key} differ from the frozen ones: a template, the task "
        "generator or the history renderer has changed, so this run no longer "
        "reproduces from this code"
    )


def test_frozen_files_are_up_to_date() -> None:
    """``freeze_prompts --check`` passes, covering the readable sample too."""
    assert freeze_prompts.main(["--check"]) == 0


def test_one_model_call_per_recorded_message() -> None:
    """Reconstruction accounts for every recorded message, with no extras."""
    path = STUDY_DIR / "runs/20260910T065248Z_primary/episodes_communication.jsonl"
    env = env_for_run(path.parent)
    episodes = freeze_prompts._load(path)
    for episode in episodes:
        calls = reconstruct(episode, task_for(episode, env))
        assert len(calls) == len(episode.messages)
        assert all(len(call) == 2 for call in calls), "every call is one system + one user message"
        assert all(call[0].role == "system" and call[1].role == "user" for call in calls)


def test_a_changed_template_is_caught(monkeypatch: pytest.MonkeyPatch) -> None:
    """Negative control: editing a prompt template must break the digest.

    Without this, a reconstruction that had quietly stopped depending on the
    templates would still pass every test above.
    """
    path = STUDY_DIR / "runs/20260910T065248Z_primary/episodes_communication.jsonl"
    env = env_for_run(path.parent)
    episodes = freeze_prompts._load(path)
    before = digest(episodes, env)

    monkeypatch.setattr(engine, "TEAM_SYSTEM_PROMPT", engine.TEAM_SYSTEM_PROMPT + " Please.")
    assert digest(episodes, env) != before

    monkeypatch.undo()
    assert digest(episodes, env) == before


def test_rule_arm_prompts_differ_from_the_primary_run_only_by_the_statement() -> None:
    """The rule arm's only prompt change is the task statement at the top.

    This is the study's whole claim, so it is asserted rather than described:
    strip :data:`~grapevine.rollout.engine.TASK_STATEMENT` from the rule arm's
    prompts and they are byte-identical to the primary run's, for the same task
    and the same turn.
    """
    primary = STUDY_DIR / "runs/20260910T065248Z_primary/episodes_communication.jsonl"
    rule = STUDY_DIR / "runs/20260913T013826Z_rule_arm/episodes_communication_rule.jsonl"
    by_id = {
        e.task_id: e
        for e in freeze_prompts._load(primary)
        if e.task_id in {x.task_id for x in freeze_prompts._load(rule)}
    }
    assert len(by_id) == 100, "the rule arm should pair with 100 primary tasks"

    env = env_for_run(rule.parent)
    compared = 0
    for rule_episode in freeze_prompts._load(rule):
        task = task_for(rule_episode, env)
        statement = engine.TASK_STATEMENT.format(question=task.question) + "\n\n"
        rule_first = reconstruct(rule_episode, task)[0]
        primary_first = reconstruct(by_id[rule_episode.task_id], task)[0]

        assert rule_first[0].content == primary_first[0].content, "system prompts match"
        assert statement in rule_first[1].content, "the rule arm states the task"
        assert statement not in primary_first[1].content, "the primary run does not"
        assert rule_first[1].content.replace(statement, "") == primary_first[1].content
        compared += 1
    assert compared == 100
