"""Freeze this study's prompts, so a template edit cannot pass unnoticed.

    python -m studies.underspecification.freeze_prompts            # regenerate
    python -m studies.underspecification.freeze_prompts --check    # verify

The committed episodes record the models' responses but not the prompts that
produced them, so nothing in the repository would notice if a template changed
and the runs stopped reproducing from the code. This module closes that gap in
two ways:

* ``prompts_golden.json`` holds one SHA-256 per committed ``(run, condition)``
  pair, taken over every reconstructed prompt byte of every episode in it. That
  is full coverage of all committed episodes in a few kilobytes.
* ``prompts_sample.md`` holds the complete prompt text for one task across every
  condition, so a reader can see what the models were actually sent instead of
  trusting a hash. ``docs/audit.md``'s appendix did this by hand for the same
  task; this file is generated.

``tests/test_study_prompts.py`` runs the ``--check`` path, so CI fails on any
drift in the templates, the generator, or the history renderer.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from grapevine.rollout.engine import Episode
from studies.underspecification.prompts import (
    as_plain,
    digest,
    env_for_run,
    reconstruct,
    task_for,
)

STUDY_DIR = Path(__file__).resolve().parent
GOLDEN_PATH = STUDY_DIR / "prompts_golden.json"
SAMPLE_PATH = STUDY_DIR / "prompts_sample.md"

#: The task whose full prompts are written out for human reading. 1006 is the
#: task ``docs/audit.md``'s appendix uses: the primary C run got it wrong and
#: the rule arm got it right, so the diff between those two prompts is the
#: finding this study is about.
SAMPLE_TASK_ID = "hidden_profile-1006"


def _episode_files(root: Path) -> list[Path]:
    """Every committed episode file, in a stable order."""
    return sorted(root.glob("runs/*/episodes_*.jsonl"))


def _load(path: Path) -> list[Episode]:
    """Load one episode file."""
    return [
        Episode.from_dict(json.loads(line))
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def _key(path: Path) -> str:
    """The ``<run>/<condition>`` key a digest is stored under."""
    return f"{path.parent.name}/{path.stem.removeprefix('episodes_')}"


def build_golden(root: Path) -> dict[str, object]:
    """Compute one prompt digest per committed ``(run, condition)`` pair."""
    conditions: dict[str, object] = {}
    for path in _episode_files(root):
        episodes = _load(path)
        conditions[_key(path)] = {
            "n_episodes": len(episodes),
            "sha256": digest(episodes, env_for_run(path.parent)),
        }
    return {
        "_comment": (
            "SHA-256 over every reconstructed prompt byte of every committed episode, "
            "one digest per (run, condition). Regenerate with "
            "'python -m studies.underspecification.freeze_prompts'. A changed digest "
            "means a prompt template, the task generator or the history renderer "
            "changed, and the committed runs no longer reproduce from this code."
        ),
        "conditions": conditions,
    }


def build_sample(root: Path) -> str:
    """Render every prompt sent for :data:`SAMPLE_TASK_ID`, condition by condition."""
    lines = [
        f"# Prompts for `{SAMPLE_TASK_ID}`, every condition",
        "",
        "Generated by `python -m studies.underspecification.freeze_prompts`. Do not",
        "edit by hand: `tests/test_study_prompts.py` regenerates this file and fails",
        "on any difference.",
        "",
        "These are the exact strings sent to the model, reconstructed by calling the",
        "same prompt builders the rollout engine calls. The task itself is",
        "regenerated from its seed and checked against what the episode recorded.",
        "",
        f"Conditions where `{SAMPLE_TASK_ID}` was not run are absent.",
        "",
    ]
    for path in _episode_files(root):
        episodes = [e for e in _load(path) if e.task_id == SAMPLE_TASK_ID]
        if not episodes:
            continue
        episode = episodes[0]
        task = task_for(episode, env_for_run(path.parent))
        calls = as_plain(reconstruct(episode, task))
        lines += [
            "---",
            "",
            f"## `{_key(path)}`",
            "",
            f"- Gold answer: **{episode.gold_answer}** · "
            f"team answered: **{episode.team_answer}** · "
            f"correct: **{episode.correct}**",
            f"- Task statement shown: **{bool(episode.config.get('show_task'))}** · "
            f"prompt style: **{episode.config.get('prompt_style')}** · "
            f"full-info presentation: **{episode.config.get('full_info_presentation')}**",
            f"- {len(calls)} model call(s).",
            "",
        ]
        for i, (call, recorded) in enumerate(zip(calls, episode.messages, strict=True), start=1):
            lines += [
                f"### Call {i} — agent {recorded.agent_id}, round {recorded.round_no}, "
                f"produced the `{recorded.role}` message",
                "",
            ]
            for message in call:
                lines += [
                    f"{message['role'].capitalize()}:",
                    "",
                    "```text",
                    message["content"],
                    "```",
                    "",
                ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Regenerate the frozen prompts, or verify them with ``--check``."""
    parser = argparse.ArgumentParser(
        prog="python -m studies.underspecification.freeze_prompts",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--root", default=str(STUDY_DIR), help="the study directory")
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed files instead of rewriting them; exit 1 on drift",
    )
    args = parser.parse_args(argv)
    root = Path(args.root)

    golden = json.dumps(build_golden(root), indent=2) + "\n"
    sample = build_sample(root)

    if args.check:
        drifted = [
            path.name
            for path, fresh in ((GOLDEN_PATH, golden), (SAMPLE_PATH, sample))
            if not path.exists() or path.read_text(encoding="utf-8") != fresh
        ]
        if drifted:
            print(
                "prompt drift in: "
                + ", ".join(drifted)
                + "\nThe prompts this code builds no longer match the frozen ones, so the\n"
                "committed runs do not reproduce from it. Either revert the change, or\n"
                "run 'python -m studies.underspecification.freeze_prompts' and explain\n"
                "in the commit message why the study's prompts moved."
            )
            return 1
        print(f"prompts unchanged: {GOLDEN_PATH.name}, {SAMPLE_PATH.name}")
        return 0

    GOLDEN_PATH.write_text(golden, encoding="utf-8")
    SAMPLE_PATH.write_text(sample, encoding="utf-8")
    print(f"wrote {GOLDEN_PATH.name} and {SAMPLE_PATH.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
