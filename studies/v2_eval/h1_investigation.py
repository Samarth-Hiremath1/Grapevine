"""The investigation the pre-registration's H1 reading requires.

    python -m studies.v2_eval.h1_investigation            # regenerate
    python -m studies.v2_eval.h1_investigation --check    # verify

The primary run put ``gpt-4o-mini``'s ``no_communication``/unstated cell above
chance (lower bound 35.0% against 25%). Section 10 of the pre-registration says
that is a gap in the audit battery, to be investigated and reported before
anything else.

This script tests one candidate explanation offline, on the committed run and
the generator: a single agent that applies the scoring rule to its *private*
facts alone. Every private supporting fact in ``hidden_profile_v2`` supports the
gold option by construction, and the battery's ``named_in_my_private_units``
solver counts option names, which v2 equalises, rather than supporting facts.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from grapevine.protocol import AgentView
from studies.v2_eval.design import DESIGN, ENVIRONMENT

STUDY_DIR = Path(__file__).resolve().parent
RUN_DIR = STUDY_DIR / "runs" / "20261116T091238Z_primary"
OUT_PATH = STUDY_DIR / "h1_investigation.md"
MODELS = ("gpt-5.6-luna", "gpt-6-luna", "gpt-4o-mini")


def private_scoring_rule(view: AgentView, options: Sequence[str]) -> str | None:
    """Apply the scoring rule to one agent's private units only.

    Args:
        view (AgentView): The agent's view.
        options (Sequence[str]): The answer space.

    Returns:
        str | None: The option with the most private supporting facts, or None on a tie.
    """
    counts = Counter(u.supports for u in view.private if u.supports)
    if not counts:
        return None
    top = max(counts.values())
    winners = [o for o in options if counts[o] == top]
    return winners[0] if len(winners) == 1 else None


def investigate() -> dict[str, Any]:
    """Every number in the report, computed from the generator and the committed run.

    Returns:
        dict[str, Any]: The solver's per-agent accuracy and the observed single-agent votes.
    """
    agents = gold = 0
    for seed in DESIGN.primary_seeds:
        task = ENVIRONMENT.generate(seed)
        for view in task.views:
            agents += 1
            gold += private_scoring_rule(view, task.answer_space) == task.gold_answer
    episodes = [
        json.loads(line)
        for line in (RUN_DIR / "episodes.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    votes: dict[str, dict[str, dict[str, int]]] = {}
    for model in MODELS:
        for objective in ("stated", "unstated"):
            rows = [e for e in episodes if e["model"] == model
                    and e["condition"] == "no_communication" and e["objective"] == objective]
            cast = [(v, e) for e in rows for v in e["votes"]]
            n_gold = sum(v == e["gold"] for v, e in cast)
            n_decoy = sum(v == e["decoy"] for v, e in cast)
            votes.setdefault(model, {})[objective] = {
                "votes": len(cast), "gold": n_gold, "decoy": n_decoy,
                "other": len(cast) - n_gold - n_decoy,
            }
    return {"solver_agents": agents, "solver_gold": gold, "votes": votes}


def markdown(result: dict[str, Any]) -> str:
    """The investigation as a report.

    Args:
        result (dict[str, Any]): Output of :func:`investigate`.

    Returns:
        str: Markdown text.
    """
    lines = [
        "# H1 investigation: a gap in the audit battery",
        "",
        "Generated by `python -m studies.v2_eval.h1_investigation`. Do not edit by hand.",
        "",
        "## Solver the battery lacks",
        "",
        "Apply the scoring rule to one agent's private facts alone, on the 100 primary",
        f"tasks: gold for **{result['solver_gold']}/{result['solver_agents']}** agents.",
        "",
        "## Single-agent votes in `no_communication`, from the primary run",
        "",
        "| Model | Objective | Votes | Gold | Decoy | Other |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for model, by_objective in result["votes"].items():
        for objective, v in by_objective.items():
            lines.append(f"| {model} | {objective} | {v['votes']} | {v['gold']} | "
                         f"{v['decoy']} | {v['other']} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Regenerate the report, or verify it with ``--check``.

    Args:
        argv (list[str] | None): Command-line arguments.

    Returns:
        int: Exit code.
    """
    parser = argparse.ArgumentParser(prog="python -m studies.v2_eval.h1_investigation")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = markdown(investigate())
    if args.check:
        same = OUT_PATH.exists() and OUT_PATH.read_text(encoding="utf-8") == text
        print("h1_investigation.md " + ("unchanged" if same else "has drifted"))
        return 0 if same else 1
    OUT_PATH.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
