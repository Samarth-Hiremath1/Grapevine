"""Freeze the pre-registered prompts, before any run.

    python -m studies.v2_eval.freeze            # regenerate
    python -m studies.v2_eval.freeze --check    # verify; CI runs this

Writes ``prompts_sample.md`` -- the full text of every opening prompt for the
first primary task, in all six cells -- and ``prompts_digest.json``, one SHA-256
over the opening prompts of every pilot and primary task in every cell. The
pre-registration records the digest, so "the exact prompts" is a checkable claim
rather than a description.

Only opening prompts can be frozen in advance: later discussion turns embed what
the model said, which does not exist yet. Their templates are frozen instead, as
part of ``design.py``, and their filled-in text is logged per call by the runner.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from studies.v2_eval.design import CELLS, DESIGN, ENVIRONMENT, opening_prompts

STUDY_DIR = Path(__file__).resolve().parent
SAMPLE_PATH = STUDY_DIR / "prompts_sample.md"
DIGEST_PATH = STUDY_DIR / "prompts_digest.json"


def digest() -> dict[str, object]:
    """One digest per phase over every opening prompt of every task and cell."""
    out: dict[str, object] = {
        "_comment": (
            "SHA-256 over the opening prompts of every task in every cell, per phase. "
            "Recorded in docs/prereg/hidden_profile_v2_eval.md before any run. "
            "Regenerate with 'python -m studies.v2_eval.freeze'."
        )
    }
    for phase in ("pilot", "primary"):
        h = hashlib.sha256()
        n = 0
        for seed in DESIGN.seeds(phase):
            task = ENVIRONMENT.generate(seed)
            for cell in CELLS:
                for prompt in opening_prompts(task, *cell):
                    h.update(json.dumps([seed, *cell, prompt], ensure_ascii=False).encode("utf-8"))
                    n += 1
        out[phase] = {"n_prompts": n, "sha256": h.hexdigest()}
    return out


def sample() -> str:
    """Every opening prompt for the first primary task, in full."""
    seed = DESIGN.primary_seeds[0]
    task = ENVIRONMENT.generate(seed)
    lines = [
        f"# Pre-registered opening prompts for `{task.task_id}`",
        "",
        "Generated by `python -m studies.v2_eval.freeze`. Do not edit by hand; CI",
        "regenerates this file and fails on any difference.",
        "",
        f"Gold answer, from the generator's construction: **{task.gold_answer}**. "
        f"Decoy: **{task.metadata['decoy_option']}**. Domain: "
        f"`{task.metadata['domain']}`.",
        "",
        "Later discussion turns embed what the model said and cannot be frozen in",
        "advance; their templates are in `design.py` and their text is logged per call.",
        "",
    ]
    for condition, objective in CELLS:
        prompts = opening_prompts(task, condition, objective)
        lines += ["---", "", f"## `{condition}`, objective {objective}", "",
                  f"{len(prompts)} opening call(s).", ""]
        for i, prompt in enumerate(prompts, start=1):
            lines += [f"### Call {i}", "", "```text", prompt, "```", ""]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Regenerate the frozen prompts, or verify them with ``--check``."""
    parser = argparse.ArgumentParser(prog="python -m studies.v2_eval.freeze")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    fresh_digest = json.dumps(digest(), indent=2) + "\n"
    fresh_sample = sample()
    if args.check:
        drifted = [
            path.name
            for path, fresh in ((DIGEST_PATH, fresh_digest), (SAMPLE_PATH, fresh_sample))
            if not path.exists() or path.read_text(encoding="utf-8") != fresh
        ]
        if drifted:
            print("pre-registered prompts have drifted: " + ", ".join(drifted)
                  + ". The pre-registration no longer describes what the runner sends.")
            return 1
        print(f"pre-registered prompts unchanged: {DIGEST_PATH.name}, {SAMPLE_PATH.name}")
        return 0
    DIGEST_PATH.write_text(fresh_digest, encoding="utf-8")
    SAMPLE_PATH.write_text(fresh_sample, encoding="utf-8")
    print(f"wrote {DIGEST_PATH.name} and {SAMPLE_PATH.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
