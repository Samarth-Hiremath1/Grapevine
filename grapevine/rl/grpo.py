"""GRPO on distributed-information environments, via TRL.

**Scaffolding, smoke-tested. No training results in this release.** Nothing
here has been run beyond a two-step CPU smoke test on a tiny random model, and
no number it produces is a result (``CLAUDE.md`` rules 2 and 3).

Written against TRL 1.18 (pinned in the ``[rl]`` extra), whose reward-function
contract was confirmed from the installed source rather than from memory: a
synchronous reward function is called on the main thread with ``prompts``,
``completions``, ``completion_ids``, ``trainer_state``, ``log_extra``,
``log_metric`` and every dataset column except ``prompt`` by name.

How a sample becomes a reward
-----------------------------

Each dataset row is one agent's opening turn on one training task. The trainer
generates that turn; the reward function then plays the rest of the episode
around it and scores it with the environment's own scorer (plus any shaping
term). So the gradient is on the opening message, and the reward is what the
whole team achieved after it.

The trained agent always speaks first in round one, which is what lets its
prompt exist before the episode does (see
:func:`~grapevine.rl.rollout.speaking_order`).

Two modes
---------

``frozen_partners``
    The policy plays the roles in ``trainable_agents``; every other role is
    played by a partner that cannot change during training -- a separately
    loaded frozen copy, an external endpoint, or a scripted stub. Later turns of
    the *trained* role are sampled from the current policy without gradient.
``self_play`` (``partners.kind: self``)
    One policy plays every agent, and every agent's opening turn is a training
    sample. Turns other than the sampled one are generated by the current
    policy without gradient. Partners are **not** frozen in this mode, by
    definition, and the manifest says so.

What is deliberately not here: TRL's experimental ``rollout_func`` (which would
put gradient on every turn of an episode), counterfactual credit assignment,
vLLM generation, and multi-GPU. See ``docs/rl.md``.
"""

from __future__ import annotations

import json
import platform
import subprocess
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from grapevine.protocol import DistributedTask, Environment
from grapevine.rl.config import RLConfig, load_config, make_environment
from grapevine.rl.gate import GateResult, audit_gate
from grapevine.rl.partners import HFClient, render_plain
from grapevine.rl.rollout import Trajectory, opening_messages, run_episode_sync
from grapevine.rollout.client import LLMClient

__all__ = [
    "RunContext",
    "build_dataset_rows",
    "make_reward_function",
    "prepare",
    "train",
]


@dataclass
class RunContext:
    """Everything a run needs, assembled before the trainer exists.

    Attributes:
        config: The parsed configuration.
        env: The environment.
        gate: The audit gate's decision.
        train_seeds: The seeds the dataset is built from.
        partner: The partner client, or ``None`` in self-play.
        policy: The client wrapping the trainer's live model. Bound after the
            trainer is constructed, because under LoRA the trainer wraps the
            model it was given and only the wrapped one carries the adapter.
        trajectories: Every episode played during training, for the log.
    """

    config: RLConfig
    env: Environment
    gate: GateResult
    train_seeds: tuple[int, ...]
    partner: LLMClient | None = None
    policy: LLMClient | None = None
    trajectories: list[Trajectory] = field(default_factory=list)

    @property
    def synthetic(self) -> bool:
        """True when scripted partners played any role."""
        return self.config.partners.kind == "scripted"


def _git(*args: str) -> str:
    try:
        return subprocess.run(
            ["git", *args], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _provenance() -> dict[str, Any]:
    """Commit, dirtiness and library versions, captured at the start of a run."""
    versions: dict[str, str] = {}
    for module in ("trl", "peft", "torch", "transformers", "datasets", "accelerate"):
        try:
            versions[module] = __import__(module).__version__
        except ImportError:
            versions[module] = "not installed"
    from grapevine import __version__

    return {
        "git_commit": _git("rev-parse", "HEAD"),
        "git_dirty": bool(_git("status", "--porcelain")),
        "python": platform.python_version(),
        "grapevine": __version__,
        "libraries": versions,
    }


def prepare(config: RLConfig, *, allow_flagged: bool = False) -> RunContext:
    """Validate a run without loading a model: environment, seeds, audit gate.

    This is the whole of ``--dry-run``, and it is the first thing a real run
    does, so a run that would be refused is refused before any download.

    Raises:
        AuditGateError: If the environment is flagged and ``allow_flagged`` is
            false.
        ValueError: If the environment has no seed split, or too few training
            seeds for ``n_train_tasks``.
    """
    env = make_environment(config.environment, config.environment_config)
    gate = audit_gate(
        env, config.reward, n_tasks=config.audit_n_tasks, allow_flagged=allow_flagged
    )
    split = env.seed_split()
    assert split is not None  # audit_gate already refused a split-less environment
    if config.n_train_tasks > len(split.train):
        raise ValueError(
            f"n_train_tasks={config.n_train_tasks} exceeds the {len(split.train)} training "
            f"seeds {env.name} declares"
        )
    seeds = tuple(split.train[: config.n_train_tasks])
    leaked = [s for s in seeds if s in split.eval or s in split.pilot]
    if leaked:  # cannot happen while SeedSplit refuses overlap; checked anyway
        raise ValueError(f"training seeds include held-out seeds {leaked[:5]}")
    return RunContext(config=config, env=env, gate=gate, train_seeds=seeds)


def build_dataset_rows(
    ctx: RunContext, *, conversational: bool
) -> list[dict[str, Any]]:
    """One row per (training task, trainable agent): that agent's opening prompt.

    Args:
        ctx: The prepared run.
        conversational: Emit chat messages for TRL to template, rather than a
            plain string. Used when the tokenizer has a chat template.

    Returns:
        Rows with ``prompt``, ``seed`` and ``trainable_agent``. TRL forwards the
        last two to the reward function by name.
    """
    rows: list[dict[str, Any]] = []
    for seed in ctx.train_seeds:
        task = ctx.env.generate(seed)
        for agent_id in ctx.config.trainable_agents:
            messages = opening_messages(task, agent_id, ctx.config.rollout)
            prompt: Any = (
                [{"role": m.role, "content": m.content} for m in messages]
                if conversational
                else render_plain(messages)
            )
            rows.append({"prompt": prompt, "seed": seed, "trainable_agent": agent_id})
    return rows


def _completion_text(completion: Any) -> str:
    """A TRL completion, which is a string or a list of chat messages, as text."""
    if isinstance(completion, str):
        return completion
    if isinstance(completion, list) and completion and isinstance(completion[-1], dict):
        return str(completion[-1].get("content", ""))
    return str(completion)


def make_reward_function(ctx: RunContext) -> Callable[..., list[float]]:
    """The TRL reward function for a prepared run.

    For each completion it regenerates the task from its seed, plays the rest of
    the episode with the configured partners, and returns the trajectory's
    reward. Every trajectory is kept on ``ctx.trajectories`` for the run log.
    """
    config = ctx.config

    def grapevine_team_reward(
        prompts: Sequence[Any],
        completions: Sequence[Any],
        seed: Sequence[int],
        trainable_agent: Sequence[int],
        **_: Any,
    ) -> list[float]:
        if ctx.policy is None:
            raise RuntimeError("the policy client was never bound to the trainer's model")
        rewards: list[float] = []
        for completion, task_seed, agent in zip(completions, seed, trainable_agent, strict=True):
            task: DistributedTask = ctx.env.generate(int(task_seed))
            clients: dict[int, LLMClient] = {}
            for other in range(task.n_agents):
                if config.self_play or other == int(agent) or other in config.trainable_agents:
                    clients[other] = ctx.policy
                else:
                    assert ctx.partner is not None
                    clients[other] = ctx.partner
            trajectory = run_episode_sync(
                task,
                clients,
                settings=config.rollout,
                reward=config.reward,
                first_speaker=int(agent),
                fixed_openings={int(agent): _completion_text(completion)},
                trainable_agents=[int(agent)],
                environment=ctx.env.name,
                environment_version=ctx.env.version,
                seed=int(task_seed),
            )
            ctx.trajectories.append(trajectory)
            rewards.append(trajectory.reward.total)
        return rewards

    return grapevine_team_reward


def _grpo_args(config: RLConfig) -> Any:
    from trl import GRPOConfig

    args = dict(config.grpo)
    args.setdefault("report_to", "none")
    args.setdefault("save_strategy", "no")
    args.setdefault("use_vllm", False)
    return GRPOConfig(output_dir=config.output_dir, seed=config.seed, **args)


def build_trainer(
    ctx: RunContext,
    *,
    model: Any = None,
    tokenizer: Any = None,
    extra_reward_funcs: Sequence[Callable[..., list[float]]] = (),
) -> Any:
    """Construct the ``GRPOTrainer`` for a prepared run.

    Args:
        ctx: From :func:`prepare`.
        model: An already-loaded policy, mainly for tests. Loaded from
            ``config.model`` otherwise.
        tokenizer: Its tokenizer.
        extra_reward_funcs: Additional TRL reward functions, summed with the
            team reward. For tests that need a completion-dependent signal.

    Returns:
        The trainer, with ``ctx.policy`` bound to the model it actually updates.
    """
    from datasets import Dataset
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from trl import GRPOTrainer

    config = ctx.config
    if tokenizer is None:
        tokenizer = AutoTokenizer.from_pretrained(config.model)
    tokenizer.padding_side = "left"  # TRL requires left padding for generation
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    if model is None:
        model = AutoModelForCausalLM.from_pretrained(config.model)

    # Partners are built *before* the trainer and from a fresh load, never from
    # `model`: sharing that object is exactly the v0 isolation bug.
    if not config.self_play:
        ctx.partner = config.partners.build(policy_name=config.model)

    conversational = bool(getattr(tokenizer, "chat_template", None))
    dataset = Dataset.from_list(build_dataset_rows(ctx, conversational=conversational))
    trainer = GRPOTrainer(
        model=model,
        reward_funcs=[make_reward_function(ctx), *extra_reward_funcs],
        args=_grpo_args(config),
        train_dataset=dataset,
        processing_class=tokenizer,
        peft_config=config.lora.to_peft() if config.lora else None,
    )
    # Bind to trainer.model, not `model`: under LoRA the trainer wraps the model
    # it was given, and only the wrapped one has the adapter being trained.
    ctx.policy = HFClient(trainer.model, tokenizer, model_name=config.model, frozen=False)
    return trainer


def write_manifest(
    ctx: RunContext,
    path: Path,
    *,
    started: str,
    provenance_start: Mapping[str, Any],
    trainer: Any = None,
    dry_run: bool = False,
) -> dict[str, Any]:
    """Write the run manifest, and return it.

    Records what the brief requires of every training run: model, seed,
    environment version, Validity Card hash, reward config, and whether partners
    were frozen -- plus the gate's decision, provenance at start and end, and
    whether the run is reportable at all.
    """
    config = ctx.config
    reasons: list[str] = []
    if ctx.synthetic:
        reasons.append("scripted partners: every trajectory is synthetic (CLAUDE.md rule 2)")
    if config.preregistration is None:
        reasons.append("no pre-registration (CLAUDE.md rule 4)")
    if dry_run:
        reasons.append("dry run: nothing was trained")
    if ctx.gate.allowed_flagged:
        reasons.append(
            "trained on a flagged environment with --allow-flagged: "
            + ", ".join(ctx.gate.card.flagged_checks)
        )
    manifest = {
        "kind": "grapevine.rl.run/1",
        "started_utc": started,
        "finished_utc": datetime.now(UTC).isoformat(timespec="seconds"),
        "dry_run": dry_run,
        "model": config.model,
        "seed": config.seed,
        "environment": {
            "name": ctx.env.name,
            "version": ctx.env.version,
            "config": dict(ctx.env.config_summary()),
        },
        "audit_gate": ctx.gate.to_dict(),
        "reward": config.reward.to_dict(),
        "partners": config.partners.to_dict(),
        "partners_frozen": config.partners.frozen,
        "mode": "self_play" if config.self_play else "frozen_partners",
        "trainable_agents": list(config.trainable_agents),
        "train_seeds": [ctx.train_seeds[0], ctx.train_seeds[-1] + 1] if ctx.train_seeds else [],
        "config": config.summary(),
        "provenance_start": dict(provenance_start),
        "provenance_end": _provenance(),
        "global_step": int(trainer.state.global_step) if trainer is not None else 0,
        "n_episodes_played": len(ctx.trajectories),
        "synthetic": ctx.synthetic,
        "reportable": not reasons,
        "not_reportable_because": reasons,
        "results": (
            "none: this release contains GRPO integration, smoke-tested; no training results"
        ),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest


def train(
    config_path: str | Path,
    *,
    allow_flagged: bool = False,
    dry_run: bool = False,
) -> dict[str, Any]:
    """Run GRPO from a config file and return the run manifest.

    The audit gate runs first. ``dry_run`` stops after it, before any model is
    loaded, and still writes a manifest saying what the run would have been.
    """
    started = datetime.now(UTC).isoformat(timespec="seconds")
    provenance_start = _provenance()
    config = load_config(config_path)
    ctx = prepare(config, allow_flagged=allow_flagged)
    out = Path(config.output_dir)

    if dry_run:
        return write_manifest(
            ctx, out / "manifest.json", started=started,
            provenance_start=provenance_start, dry_run=True,
        )

    trainer = build_trainer(ctx)
    trainer.train()

    if config.save_policy:
        trainer.save_model(str(out / "policy"))
    with (out / "trajectories.jsonl").open("w", encoding="utf-8") as fh:
        for trajectory in ctx.trajectories:
            fh.write(json.dumps(trajectory.to_dict(), ensure_ascii=False) + "\n")
    return write_manifest(
        ctx, out / "manifest.json", started=started,
        provenance_start=provenance_start, trainer=trainer,
    )


def main(argv: list[str] | None = None) -> int:
    """``python -m grapevine.rl.grpo <config.yaml>``; prefer ``grapevine train``."""
    import argparse

    parser = argparse.ArgumentParser(prog="grapevine train", description=__doc__)
    parser.add_argument("config")
    parser.add_argument("--allow-flagged", action="store_true")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)
    manifest = train(args.config, allow_flagged=args.allow_flagged, dry_run=args.dry_run)
    print(json.dumps({k: manifest[k] for k in ("audit_gate", "reportable", "global_step")}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
